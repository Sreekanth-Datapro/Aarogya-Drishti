import React, { useCallback, useEffect, useState } from "react";
import { UserPlus } from "lucide-react";
import api from "../../services/api";
import { useLanguage } from "../../i18n/LanguageContext";
import {
  formatLocalizedDate,
  formatLocalizedDateTime,
  getAccountStatusLabel,
  getDeliveryStatusLabel,
  getLocalizedField,
  getLocalizedMasterName,
} from "../../i18n/displayLabels";
import { apiMessage } from "../../i18n/translate";
import { Alert, Badge, Button, Card, SelectField, TextField } from "../../components/ui";
import "./DistrictAdminManagement.css";

// The username and the temporary password are generated by the server
const EMPTY_FORM = {
  full_name: "",
  email: "",
  phone: "",
  district_id: "",
};

function getStatusTone(status) {
  if (status === "ACTIVE") return "success";
  if (status === "PENDING_SETUP") return "warning";
  return "neutral";
}

// Setup progress of an account: a translation key and a badge colour
function getSetupStatus(status, passwordPending) {
  if (status === "PENDING_SETUP") {
    return {
      key: passwordPending ? "districtAdmins.setupPasswordPending" : "districtAdmins.setupMfaPending",
      tone: "warning",
    };
  }
  if (status === "ACTIVE") return { key: "districtAdmins.setupComplete", tone: "success" };
  return { key: "districtAdmins.setupUnavailable", tone: "neutral" };
}

function getDeliveryTone(status) {
  if (status === "SENT") return "success";
  if (status === "FAILED") return "danger";
  return "neutral";
}

export default function DistrictAdminManagement() {
  const { t, tm, language } = useLanguage();
  const [districts, setDistricts] = useState([]);
  const [admins, setAdmins] = useState([]);
  const [form, setForm] = useState(EMPTY_FORM);
  const [formErrors, setFormErrors] = useState({});
  const [districtChoices, setDistrictChoices] = useState({});
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [workingAction, setWorkingAction] = useState("");
  const [error, setError] = useState("");
  const [message, setMessage] = useState("");

  const loadData = useCallback(async () => {
    setLoading(true);
    setError("");
    try {
      const [districtResponse, adminResponse] = await Promise.all([
        api.get("/admin/districts"),
        api.get("/admin/district-admins"),
      ]);
      setDistricts(districtResponse.data.districts);
      setAdmins(adminResponse.data.district_admins);
      setDistrictChoices(Object.fromEntries(
        adminResponse.data.district_admins.map((admin) => [
          admin.id,
          admin.district_id ? String(admin.district_id) : "",
        ])
      ));
    } catch (requestError) {
      setError(apiMessage(requestError, "districtAdmins.loadFailed"));
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    loadData();
  }, [loadData]);

  const updateForm = (field, value) => {
    setForm((current) => ({ ...current, [field]: value }));
    setFormErrors((current) => ({ ...current, [field]: "" }));
  };

  // Field errors are translation keys, shown with tm() in the current language
  const validateForm = () => {
    const errors = {};
    const phone = form.phone.trim();
    const email = form.email.trim();

    if (!form.full_name.trim() || form.full_name.trim().length > 150) {
      errors.full_name = "districtAdmins.invalidName";
    }
    // The login details are emailed, so the email address is required
    if (!email) {
      errors.email = "districtAdmins.emailRequired";
    } else if (email.length > 254 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
      errors.email = "districtAdmins.invalidEmail";
    }
    if (phone && !/^\d{10,11}$/.test(phone)) {
      errors.phone = "districtAdmins.invalidPhone";
    }
    if (!form.district_id) errors.district_id = "districtAdmins.districtRequired";

    setFormErrors(errors);
    return Object.keys(errors).length === 0;
  };

  const createAdmin = async (event) => {
    event.preventDefault();
    setError("");
    setMessage("");
    if (!validateForm()) return;

    setSaving(true);
    try {
      const response = await api.post("/admin/district-admins", {
        full_name: form.full_name.trim(),
        email: form.email.trim(),
        phone: form.phone.trim(),
        district_id: Number(form.district_id),
      });
      const emailSent = response.data.delivery_status?.email?.status === "SENT";
      setMessage({
        key: emailSent ? "districtAdmins.createdEmailSent" : "districtAdmins.createdEmailNotSent",
        values: { username: response.data.district_admin?.username || "" },
      });
      setForm(EMPTY_FORM);
      setFormErrors({});
      await loadData();
    } catch (requestError) {
      if (requestError.response?.status === 409) {
        setError("districtAdmins.duplicateUsername");
      } else {
        setError(apiMessage(requestError, "districtAdmins.createFailed"));
      }
    } finally {
      setSaving(false);
    }
  };

  const mapAdmin = async (admin) => {
    const districtId = districtChoices[admin.id];
    if (!districtId) {
      setError("districtAdmins.chooseDistrictFirst");
      setMessage("");
      return;
    }

    setError("");
    setMessage("");
    setWorkingAction(`map-${admin.id}`);
    try {
      await api.patch(`/admin/district-admins/${admin.id}/district`, {
        district_id: Number(districtId),
      });
      setMessage({ key: "districtAdmins.mappingSaved", values: { name: admin.full_name } });
      await loadData();
    } catch (requestError) {
      setError(apiMessage(requestError, "districtAdmins.mappingFailed"));
    } finally {
      setWorkingAction("");
    }
  };

  const reissueSetup = async (admin) => {
    setError("");
    setMessage("");
    setWorkingAction(`setup-${admin.id}`);
    try {
      const response = await api.post(`/admin/district-admins/${admin.id}/setup-token`);
      setMessage(response.data.message);
      await loadData();
    } catch (requestError) {
      setError(apiMessage(requestError, "districtAdmins.reissueFailed"));
    } finally {
      setWorkingAction("");
    }
  };

  // channel: "email" | "sms"
  const retryDelivery = async (admin, channel) => {
    setError("");
    setMessage("");
    setWorkingAction(`retry-${channel}-${admin.id}`);
    try {
      const response = await api.post(
        `/admin/district-admins/${admin.id}/setup-delivery/${channel}/retry`
      );
      setMessage(response.data.message || `districtAdmins.retryDone.${channel}`);
      await loadData();
    } catch (requestError) {
      setError(apiMessage(requestError, `districtAdmins.retryFailed.${channel}`));
    } finally {
      setWorkingAction("");
    }
  };

  const districtOptions = districts.map((district) => (
    <option key={district.id} value={district.id}>{getLocalizedMasterName(district, language)}</option>
  ));

  return (
    <div className="district-admin-page">
      <div className="page-header">
        <div>
          <h1 className="page-title">{t("districtAdmins.title")}</h1>
          <p className="page-subtitle">{t("districtAdmins.subtitle")}</p>
        </div>
        <a className="district-admin-page-cta" href="#district-admin-create">
          <UserPlus size={17} aria-hidden="true" />
          {t("districtAdmins.create")}
        </a>
      </div>

      {error && <Alert type="error">{tm(error)}</Alert>}
      {message && <Alert type="success">{tm(message)}</Alert>}

      <div className="section">
        <Alert type="warning">{t("districtAdmins.deliveryNotice")}</Alert>
      </div>

      <div className="section" id="district-admin-create">
        <Card title={t("districtAdmins.createTitle")} subtitle={t("districtAdmins.createSubtitle")}>
          <form onSubmit={createAdmin} noValidate>
            <div className="grid grid-2">
              <TextField
                id="district-admin-name"
                label={t("districtAdmins.fullName")}
                required
                maxLength={150}
                autoComplete="name"
                value={form.full_name}
                error={tm(formErrors.full_name)}
                onChange={(event) => updateForm("full_name", event.target.value)}
              />
              <TextField
                id="district-admin-phone"
                label={t("districtAdmins.phone")}
                type="tel"
                inputMode="numeric"
                maxLength={11}
                autoComplete="tel"
                optionalText={t("common.optional")}
                value={form.phone}
                error={tm(formErrors.phone)}
                onChange={(event) => updateForm("phone", event.target.value)}
              />
              <TextField
                id="district-admin-email"
                label={t("districtAdmins.email")}
                type="email"
                required
                maxLength={254}
                autoComplete="email"
                hint={t("districtAdmins.emailHint")}
                value={form.email}
                error={tm(formErrors.email)}
                onChange={(event) => updateForm("email", event.target.value)}
              />
              <SelectField
                id="district-admin-district"
                label={t("districtAdmins.district")}
                required
                value={form.district_id}
                error={tm(formErrors.district_id)}
                onChange={(event) => updateForm("district_id", event.target.value)}
              >
                <option value="">{t("districtAdmins.selectDistrict")}</option>
                {districtOptions}
              </SelectField>
              <SelectField
                id="district-admin-status"
                label={t("districtAdmins.accountStatus")}
                defaultValue="PENDING_SETUP"
                disabled
                hint={t("districtAdmins.accountStatusHint")}
              >
                <option value="PENDING_SETUP">{getAccountStatusLabel("PENDING_SETUP", language)}</option>
              </SelectField>
            </div>
            {districts.length === 0 && !loading && (
              <p className="district-admin-form-note">{t("districtAdmins.noDistricts")}</p>
            )}
            <div className="district-admin-form-actions">
              <Button
                type="submit"
                loading={saving}
                disabled={loading || districts.length === 0}
                icon={UserPlus}
              >
                {t("districtAdmins.createAccount")}
              </Button>
            </div>
          </form>
        </Card>
      </div>

      <div className="section" id="district-admin-list">
        <Card title={t("districtAdmins.listTitle")} subtitle={t("districtAdmins.listSubtitle")}>
          {loading ? (
            <p className="district-admin-loading" role="status">{t("districtAdmins.loading")}</p>
          ) : admins.length === 0 ? (
            <p className="district-admin-empty">
              {error ? t("districtAdmins.loadError") : t("districtAdmins.empty")}
            </p>
          ) : (
            <div className="district-admin-table-wrap">
              <table className="table">
                <thead>
                  <tr>
                    <th scope="col">{t("districtAdmins.colName")}</th>
                    <th scope="col">{t("districtAdmins.colUsername")}</th>
                    <th scope="col">{t("districtAdmins.colPhone")}</th>
                    <th scope="col">{t("districtAdmins.colDistrict")}</th>
                    <th scope="col">{t("districtAdmins.colAccountStatus")}</th>
                    <th scope="col">{t("districtAdmins.colSetupStatus")}</th>
                    <th scope="col">{t("districtAdmins.colEmailDelivery")}</th>
                    <th scope="col">{t("districtAdmins.colCreated")}</th>
                    <th scope="col">{t("districtAdmins.colActions")}</th>
                  </tr>
                </thead>
                <tbody>
                  {admins.map((admin) => {
                    const setupStatus = getSetupStatus(admin.status, admin.setup_password_pending);
                    const emailStatus = admin.email_delivery_status || "NOT_CONFIGURED";
                    return (
                      <tr key={admin.id}>
                        <td><strong>{admin.full_name}</strong></td>
                        <td>{admin.username}</td>
                        <td>{admin.phone || t("common.notProvided")}</td>
                        <td>
                          <strong>{getLocalizedField(admin, "district_name", language) || t("districtAdmins.notAssigned")}</strong>
                          <select
                            className="select district-admin-district-select"
                            aria-label={t("districtAdmins.changeDistrictFor", { name: admin.full_name })}
                            value={districtChoices[admin.id] || ""}
                            onChange={(event) => setDistrictChoices((current) => ({
                              ...current,
                              [admin.id]: event.target.value,
                            }))}
                          >
                            <option value="">{t("districtAdmins.selectDistrict")}</option>
                            {districtOptions}
                          </select>
                        </td>
                        <td>
                          <Badge tone={getStatusTone(admin.status)}>
                            {getAccountStatusLabel(admin.status || "UNKNOWN", language)}
                          </Badge>
                        </td>
                        <td>
                          <Badge tone={setupStatus.tone}>{t(setupStatus.key)}</Badge>
                          {admin.status === "PENDING_SETUP" && admin.setup_password_pending && (
                            <p className="cell-sub">
                              {admin.credentials_expires_at && new Date(admin.credentials_expires_at) > new Date()
                                ? t("districtAdmins.temporaryPasswordExpires", {
                                  date: formatLocalizedDateTime(admin.credentials_expires_at, language),
                                })
                                : t("districtAdmins.temporaryPasswordExpired")}
                            </p>
                          )}
                        </td>
                        <td>
                          <Badge tone={getDeliveryTone(emailStatus)}>{getDeliveryStatusLabel(emailStatus, language)}</Badge>
                        </td>
                        <td>{formatLocalizedDate(admin.created_at, language) || t("common.notAvailable")}</td>
                        <td>
                          <div className="table-actions">
                            <Button
                              size="sm"
                              variant="secondary"
                              loading={workingAction === `map-${admin.id}`}
                              disabled={Boolean(workingAction) || saving}
                              onClick={() => mapAdmin(admin)}
                            >
                              {t("districtAdmins.saveMapping")}
                            </Button>
                            {admin.status === "PENDING_SETUP" && (
                              <>
                                {admin.setup_password_pending && admin.email && admin.email_delivery_status !== "SENT" && (
                                  <Button
                                    size="sm"
                                    variant="ghost"
                                    loading={workingAction === `retry-email-${admin.id}`}
                                    disabled={Boolean(workingAction) || saving}
                                    onClick={() => retryDelivery(admin, "email")}
                                  >
                                    {t("districtAdmins.retryEmail")}
                                  </Button>
                                )}
                                <Button
                                  size="sm"
                                  variant="ghost"
                                  loading={workingAction === `setup-${admin.id}`}
                                  disabled={Boolean(workingAction) || saving || !admin.district_id}
                                  onClick={() => reissueSetup(admin)}
                                >
                                  {t("districtAdmins.reissue")}
                                </Button>
                              </>
                            )}
                          </div>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          )}
        </Card>
      </div>
    </div>
  );
}
